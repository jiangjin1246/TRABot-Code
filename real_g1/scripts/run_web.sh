#!/usr/bin/env bash
set -euo pipefail

# shellcheck disable=SC1091
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/common.sh"

require_executable "${FLASHHEAD_PYTHON}"
require_dir "${FLASHHEAD_SOURCE_DIR}"
require_executable "${G1_REALTIME_RUNNER}"
require_file "${G1_REALTIME_CATALOG}"
require_file "${G1_REALTIME_LIMITS}"
require_file "${G1_REALTIME_REVIEW_STORE}"

if [[ "${OVERLAY_BACKEND}" != "g1_realtime" ]]; then
  echo "OVERLAY_BACKEND must be g1_realtime for this launcher" >&2
  exit 1
fi
if [[ "${OVERLAY_DIALOGUE_SEQUENCE_MODE}" != "semantic_f17" ]]; then
  echo "Only semantic_f17 is enabled in the real-time G1 launcher" >&2
  exit 1
fi
if [[ "${G1_REALTIME_ENABLED}" != "1" ]]; then
  echo "Real G1 execution is disabled. Set G1_REALTIME_ENABLED=1 after the operator is ready." >&2
  exit 1
fi
if [[ ! -d "/sys/class/net/${G1_REALTIME_NETWORK_INTERFACE}" ]]; then
  echo "Network interface does not exist: ${G1_REALTIME_NETWORK_INTERFACE}" >&2
  exit 1
fi
if [[ "$(<"/sys/class/net/${G1_REALTIME_NETWORK_INTERFACE}/operstate")" != "up" ]]; then
  echo "Network interface ${G1_REALTIME_NETWORK_INTERFACE} is not UP; refusing to start real mode." >&2
  exit 1
fi

cd "${PROJECT_ROOT}"
exec env \
  CUDA_VISIBLE_DEVICES="${FLASHHEAD_CUDA_VISIBLE_DEVICES}" \
  FLASHHEAD_SOURCE_DIR="${FLASHHEAD_SOURCE_DIR}" \
  FLASHHEAD_PROJECT_ROOT="${FLASHHEAD_SOURCE_DIR}" \
  OVERLAY_BACKEND="${OVERLAY_BACKEND}" \
  OVERLAY_VIDEO_ENABLED="${OVERLAY_VIDEO_ENABLED}" \
  OVERLAY_DIAGNOSTICS_HOST="${OVERLAY_DIAGNOSTICS_HOST}" \
  OVERLAY_DIAGNOSTICS_PORT="${OVERLAY_DIAGNOSTICS_PORT}" \
  OVERLAY_DIALOGUE_SEQUENCE_MODE="${OVERLAY_DIALOGUE_SEQUENCE_MODE}" \
  OVERLAY_SEMANTIC_CATALOG_PATH="${OVERLAY_SEMANTIC_CATALOG_PATH}" \
  OVERLAY_SEMANTIC_PROMPT_PATH="${OVERLAY_SEMANTIC_PROMPT_PATH}" \
  OVERLAY_SEMANTIC_EXECUTE="${OVERLAY_SEMANTIC_EXECUTE}" \
  OVERLAY_SEMANTIC_FORCE_FIRST="${OVERLAY_SEMANTIC_FORCE_FIRST}" \
  OVERLAY_SEMANTIC_SESSION_NEUTRAL_ENABLED="${OVERLAY_SEMANTIC_SESSION_NEUTRAL_ENABLED}" \
  OVERLAY_SEMANTIC_LOG_PATH="${OVERLAY_SEMANTIC_LOG_PATH}" \
  OVERLAY_SEMANTIC_TAIL_GUARD_SECONDS="${OVERLAY_SEMANTIC_TAIL_GUARD_SECONDS}" \
  OVERLAY_SEMANTIC_POLL_INTERVAL="${OVERLAY_SEMANTIC_POLL_INTERVAL}" \
  OVERLAY_SEMANTIC_ACTION_TIMEOUT="${OVERLAY_SEMANTIC_ACTION_TIMEOUT}" \
  G1_REALTIME_ENABLED="${G1_REALTIME_ENABLED}" \
  G1_REALTIME_RUNNER="${G1_REALTIME_RUNNER}" \
  G1_REALTIME_CATALOG="${G1_REALTIME_CATALOG}" \
  G1_REALTIME_LIMITS="${G1_REALTIME_LIMITS}" \
  G1_REALTIME_REVIEW_STORE="${G1_REALTIME_REVIEW_STORE}" \
  G1_REALTIME_NETWORK_INTERFACE="${G1_REALTIME_NETWORK_INTERFACE}" \
  G1_REALTIME_SESSION_STARTUP_TIMEOUT="${G1_REALTIME_SESSION_STARTUP_TIMEOUT}" \
  G1_REALTIME_SESSION_IDLE_TIMEOUT="${G1_REALTIME_SESSION_IDLE_TIMEOUT}" \
  G1_REALTIME_PROCESS_STOP_TIMEOUT="${G1_REALTIME_PROCESS_STOP_TIMEOUT}" \
  OVERLAY_EXPERIMENT_RECORDING_ENABLED="${OVERLAY_EXPERIMENT_RECORDING_ENABLED}" \
  OVERLAY_EXPERIMENT_RECORDING_ROOT="${OVERLAY_EXPERIMENT_RECORDING_ROOT}" \
  OVERLAY_EXPERIMENT_RECORDING_FFMPEG="${OVERLAY_EXPERIMENT_RECORDING_FFMPEG}" \
  OVERLAY_EXPERIMENT_RECORDING_MIN_FREE_BYTES="${OVERLAY_EXPERIMENT_RECORDING_MIN_FREE_BYTES}" \
  OVERLAY_EXPERIMENT_RECORDING_MAX_SECONDS="${OVERLAY_EXPERIMENT_RECORDING_MAX_SECONDS}" \
  OVERLAY_EXPERIMENT_RECORDING_MAX_BYTES="${OVERLAY_EXPERIMENT_RECORDING_MAX_BYTES}" \
  G1_ACTIONS_ENABLED=0 \
  G1_SIMULATION_MODE=1 \
  ROBOT_ENABLED=0 \
  GEMINI_API_KEY="${GEMINI_API_KEY:-}" \
  "${FLASHHEAD_PYTHON}" app.py \
  --upstream-path "${FLASHHEAD_SOURCE_DIR}" \
  -- \
  --host "${WEB_HOST}" \
  --port "${WEB_PORT}"
