#!/usr/bin/env bash
set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO_ROOT="$(cd "${PROJECT_ROOT}/.." && pwd)"
# Conda env root; override CONDA_ENVS_DIR or the *_PYTHON variables in config.env.
CONDA_ENVS_DIR="${CONDA_ENVS_DIR:-$(conda info --base 2>/dev/null || dirname "$(dirname "${CONDA_EXE:-${HOME}/miniconda3/bin/conda}")")/envs}"

if [[ -f "${PROJECT_ROOT}/config.env" ]]; then
  # shellcheck disable=SC1091
  source "${PROJECT_ROOT}/config.env"
fi

# Python is the only dependency outside this folder: set FLASHHEAD_PYTHON in
# config.env on each machine (see requirements-woface.txt).
if [[ -z "${FLASHHEAD_PYTHON:-}" ]]; then
  if [[ -x "${CONDA_ENVS_DIR}/flashhead/bin/python" ]]; then
    FLASHHEAD_PYTHON="${CONDA_ENVS_DIR}/flashhead/bin/python"
  else
    FLASHHEAD_PYTHON="$(command -v python3 || true)"
  fi
fi
# The Web app (webrtc_app_gemini_http.py, assets/, examples/) is shared with
# the other runtimes in ../face; the Atom library is ../catalog.
FLASHHEAD_SOURCE_DIR="${FLASHHEAD_SOURCE_DIR:-${REPO_ROOT}/face}"
MOTIONLIB_DIR="${REPO_ROOT}/catalog"

WEB_HOST="${WEB_HOST:-127.0.0.1}"
WEB_PORT="${WEB_PORT:-1131}"
OVERLAY_DIAGNOSTICS_HOST="${OVERLAY_DIAGNOSTICS_HOST:-127.0.0.1}"
OVERLAY_DIAGNOSTICS_PORT="${OVERLAY_DIAGNOSTICS_PORT:-8792}"
OVERLAY_DIAGNOSTICS_URL="http://${OVERLAY_DIAGNOSTICS_HOST}:${OVERLAY_DIAGNOSTICS_PORT}"

OVERLAY_BACKEND="${OVERLAY_BACKEND:-g1_realtime}"
OVERLAY_VIDEO_ENABLED="${OVERLAY_VIDEO_ENABLED:-0}"
OVERLAY_DIALOGUE_SEQUENCE_MODE="${OVERLAY_DIALOGUE_SEQUENCE_MODE:-semantic_f17}"
OVERLAY_SEMANTIC_CATALOG_PATH="${OVERLAY_SEMANTIC_CATALOG_PATH:-${MOTIONLIB_DIR}/semantic_atom_catalog_v1.6725cb58a85b60a1b885d51a407c1ad7a5abea7d309658b2105cc0d86e264e5b.json}"
OVERLAY_SEMANTIC_PROMPT_PATH="${OVERLAY_SEMANTIC_PROMPT_PATH:-${PROJECT_ROOT}/prompts/gemini_semantic_gesture_v1.txt}"
OVERLAY_SEMANTIC_EXECUTE="${OVERLAY_SEMANTIC_EXECUTE:-1}"
OVERLAY_SEMANTIC_FORCE_FIRST="${OVERLAY_SEMANTIC_FORCE_FIRST:-1}"
OVERLAY_SEMANTIC_SESSION_NEUTRAL_ENABLED="${OVERLAY_SEMANTIC_SESSION_NEUTRAL_ENABLED:-0}"
OVERLAY_SEMANTIC_LOG_PATH="${OVERLAY_SEMANTIC_LOG_PATH:-${PROJECT_ROOT}/runtime/dialogue_semantic_f17_g1_turns.jsonl}"
OVERLAY_SEMANTIC_TAIL_GUARD_SECONDS="${OVERLAY_SEMANTIC_TAIL_GUARD_SECONDS:-0.35}"
OVERLAY_SEMANTIC_POLL_INTERVAL="${OVERLAY_SEMANTIC_POLL_INTERVAL:-0.05}"
OVERLAY_SEMANTIC_ACTION_TIMEOUT="${OVERLAY_SEMANTIC_ACTION_TIMEOUT:-45}"

G1_REALTIME_ENABLED="${G1_REALTIME_ENABLED:-0}"
G1_REALTIME_RUNNER="${G1_REALTIME_RUNNER:-${PROJECT_ROOT}/g1_bridge/build/g1_atom_motion_cli}"
G1_REALTIME_CATALOG="${G1_REALTIME_CATALOG:-${OVERLAY_SEMANTIC_CATALOG_PATH}}"
G1_REALTIME_LIMITS="${G1_REALTIME_LIMITS:-${PROJECT_ROOT}/config/g1_limits.json}"
G1_REALTIME_REVIEW_STORE="${G1_REALTIME_REVIEW_STORE:-${MOTIONLIB_DIR}/g1_reviews.json}"
G1_REALTIME_PREVIEW_ROOT="${G1_REALTIME_PREVIEW_ROOT:-${MOTIONLIB_DIR}/previews/semantic_realtime_review_v1}"
G1_REALTIME_NETWORK_INTERFACE="${G1_REALTIME_NETWORK_INTERFACE:-eno2}"
G1_REALTIME_SESSION_STARTUP_TIMEOUT="${G1_REALTIME_SESSION_STARTUP_TIMEOUT:-8}"
G1_REALTIME_SESSION_IDLE_TIMEOUT="${G1_REALTIME_SESSION_IDLE_TIMEOUT:-15}"
G1_REALTIME_PROCESS_STOP_TIMEOUT="${G1_REALTIME_PROCESS_STOP_TIMEOUT:-8}"

OVERLAY_EXPERIMENT_RECORDING_ENABLED="${OVERLAY_EXPERIMENT_RECORDING_ENABLED:-1}"
OVERLAY_EXPERIMENT_RECORDING_ROOT="${OVERLAY_EXPERIMENT_RECORDING_ROOT:-${PROJECT_ROOT}/runtime/experiment_recordings}"
OVERLAY_EXPERIMENT_RECORDING_FFMPEG="${OVERLAY_EXPERIMENT_RECORDING_FFMPEG:-ffmpeg}"
OVERLAY_EXPERIMENT_RECORDING_MIN_FREE_BYTES="${OVERLAY_EXPERIMENT_RECORDING_MIN_FREE_BYTES:-10737418240}"
OVERLAY_EXPERIMENT_RECORDING_MAX_SECONDS="${OVERLAY_EXPERIMENT_RECORDING_MAX_SECONDS:-7200}"
OVERLAY_EXPERIMENT_RECORDING_MAX_BYTES="${OVERLAY_EXPERIMENT_RECORDING_MAX_BYTES:-21474836480}"

RUNTIME_DIR="${PROJECT_ROOT}/runtime"
mkdir -p "${RUNTIME_DIR}"

require_file() {
  if [[ ! -f "$1" ]]; then
    echo "Required file is missing: $1" >&2
    exit 1
  fi
}

require_executable() {
  if [[ ! -x "$1" ]]; then
    echo "Required executable is missing: $1" >&2
    exit 1
  fi
}

require_dir() {
  if [[ ! -d "$1" ]]; then
    echo "Required directory is missing: $1" >&2
    exit 1
  fi
}
