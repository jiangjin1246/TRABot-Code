#!/usr/bin/env bash
set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO_ROOT="$(cd "${PROJECT_ROOT}/.." && pwd)"
# Conda env root; override CONDA_ENVS_DIR or the *_PYTHON variables in config.env.
CONDA_ENVS_DIR="${CONDA_ENVS_DIR:-$(conda info --base 2>/dev/null || dirname "$(dirname "${CONDA_EXE:-${HOME}/miniconda3/bin/conda}")")/envs}"

if [[ -f "${PROJECT_ROOT}/config.env" ]]; then
  # shellcheck disable=SC1091
  source "${PROJECT_ROOT}/config.env"
fi

FLASHHEAD_PYTHON="${FLASHHEAD_PYTHON:-${CONDA_ENVS_DIR}/flashhead/bin/python}"
G1_MUJOCO_PYTHON="${G1_MUJOCO_PYTHON:-${CONDA_ENVS_DIR}/g1-mujoco/bin/python}"
FLASHHEAD_SOURCE_DIR="${FLASHHEAD_SOURCE_DIR:-${REPO_ROOT}/face}"
MUJOCO_MODEL_PATH="${MUJOCO_MODEL_PATH:-${REPO_ROOT}/external/unitree_mujoco/unitree_robots/g1/scene_29dof.xml}"
G1_SOURCE_MOTION_ROOT="${G1_SOURCE_MOTION_ROOT:-${REPO_ROOT}/catalog/legacy_gestures}"
SIM_HOST="${SIM_HOST:-127.0.0.1}"
SIM_PORT="${SIM_PORT:-8765}"
WEB_HOST="${WEB_HOST:-0.0.0.0}"
WEB_PORT="${WEB_PORT:-1121}"
SIM_CUDA_VISIBLE_DEVICES="${SIM_CUDA_VISIBLE_DEVICES:-0}"
FLASHHEAD_CUDA_VISIBLE_DEVICES="${FLASHHEAD_CUDA_VISIBLE_DEVICES:-1}"
SIM_MUJOCO_GL="${SIM_MUJOCO_GL:-glfw}"
SIM_DISPLAY="${SIM_DISPLAY:-:1}"
SIM_RENDER_FPS="${SIM_RENDER_FPS:-25}"
SIM_SERVICE_URL="${SIM_SERVICE_URL:-http://${SIM_HOST}:${SIM_PORT}}"
OVERLAY_COMPOSITE_FPS="${OVERLAY_COMPOSITE_FPS:-25}"
OVERLAY_FRAME_POLL_HZ="${OVERLAY_FRAME_POLL_HZ:-25}"
OVERLAY_DIAGNOSTICS_HOST="${OVERLAY_DIAGNOSTICS_HOST:-127.0.0.1}"
OVERLAY_DIAGNOSTICS_PORT="${OVERLAY_DIAGNOSTICS_PORT:-8791}"
OVERLAY_DIAGNOSTICS_URL="http://${OVERLAY_DIAGNOSTICS_HOST}:${OVERLAY_DIAGNOSTICS_PORT}"
# semantic_f17 is the TRABot planner used in the paper (Full model).
OVERLAY_DIALOGUE_SEQUENCE_MODE="${OVERLAY_DIALOGUE_SEQUENCE_MODE:-semantic_f17}"
OVERLAY_ATOM_CATALOG_PATH="${OVERLAY_ATOM_CATALOG_PATH:-${PROJECT_ROOT}/atom_catalog_v1.json}"
OVERLAY_RANDOM_SEQUENCE_COUNT="${OVERLAY_RANDOM_SEQUENCE_COUNT:-3}"
OVERLAY_RANDOM_SEQUENCE_BASE_SEED="${OVERLAY_RANDOM_SEQUENCE_BASE_SEED:-42}"
OVERLAY_RANDOM_SEQUENCE_LOG_PATH="${OVERLAY_RANDOM_SEQUENCE_LOG_PATH:-${PROJECT_ROOT}/runtime/dialogue_atom_turns.jsonl}"
OVERLAY_RANDOM_SEQUENCE_POLL_INTERVAL="${OVERLAY_RANDOM_SEQUENCE_POLL_INTERVAL:-0.05}"
OVERLAY_RANDOM_SEQUENCE_ACTION_TIMEOUT="${OVERLAY_RANDOM_SEQUENCE_ACTION_TIMEOUT:-45}"
OVERLAY_SEMANTIC_CATALOG_PATH="${OVERLAY_SEMANTIC_CATALOG_PATH:-${REPO_ROOT}/catalog/semantic_atom_catalog_v1.6725cb58a85b60a1b885d51a407c1ad7a5abea7d309658b2105cc0d86e264e5b.json}"
OVERLAY_SEMANTIC_PROMPT_PATH="${OVERLAY_SEMANTIC_PROMPT_PATH:-${PROJECT_ROOT}/prompts/gemini_semantic_gesture_v1.txt}"
# 1 = execute the planned Atoms in MuJoCo (paper setting). With 0, semantic_f17
# still runs the complete planner in dry-run/shadow mode.
OVERLAY_SEMANTIC_EXECUTE="${OVERLAY_SEMANTIC_EXECUTE:-1}"
# Explicit opt-in: if no first Atom fits, run one closed Atom through neutral
# recovery and drop its suffix (paper setting).
OVERLAY_SEMANTIC_FORCE_FIRST="${OVERLAY_SEMANTIC_FORCE_FIRST:-1}"
OVERLAY_SEMANTIC_LOG_PATH="${OVERLAY_SEMANTIC_LOG_PATH:-${PROJECT_ROOT}/runtime/dialogue_semantic_f17_turns.jsonl}"
OVERLAY_SEMANTIC_TAIL_GUARD_SECONDS="${OVERLAY_SEMANTIC_TAIL_GUARD_SECONDS:-0.35}"
OVERLAY_SEMANTIC_POLL_INTERVAL="${OVERLAY_SEMANTIC_POLL_INTERVAL:-0.05}"
OVERLAY_SEMANTIC_ACTION_TIMEOUT="${OVERLAY_SEMANTIC_ACTION_TIMEOUT:-45}"
# The recorder feature is available by default, but capture remains idle until
# the operator explicitly clicks Record Experiment. Set ENABLED=0 as a server
# kill switch; recordings never share a public static directory.
OVERLAY_EXPERIMENT_RECORDING_ENABLED="${OVERLAY_EXPERIMENT_RECORDING_ENABLED:-1}"
OVERLAY_EXPERIMENT_RECORDING_ROOT="${OVERLAY_EXPERIMENT_RECORDING_ROOT:-${PROJECT_ROOT}/runtime/experiment_recordings}"
OVERLAY_EXPERIMENT_RECORDING_FFMPEG="${OVERLAY_EXPERIMENT_RECORDING_FFMPEG:-ffmpeg}"
OVERLAY_EXPERIMENT_RECORDING_MIN_FREE_BYTES="${OVERLAY_EXPERIMENT_RECORDING_MIN_FREE_BYTES:-10737418240}"
OVERLAY_EXPERIMENT_RECORDING_MAX_SECONDS="${OVERLAY_EXPERIMENT_RECORDING_MAX_SECONDS:-7200}"
OVERLAY_EXPERIMENT_RECORDING_MAX_BYTES="${OVERLAY_EXPERIMENT_RECORDING_MAX_BYTES:-21474836480}"
RUNTIME_DIR="${PROJECT_ROOT}/runtime"

mkdir -p "${RUNTIME_DIR}"

require_file() {
  if [[ ! -f "$1" ]]; then
    echo "Required file is missing: $1" >&2
    exit 1
  fi
}

require_dir() {
  if [[ ! -d "$1" ]]; then
    echo "Required directory is missing: $1" >&2
    exit 1
  fi
}
